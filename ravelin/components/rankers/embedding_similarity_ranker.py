"""
This module contains the EmbeddingSimilarityRanker component, which ranks documents based on their similarity to a query
using an external embedding asset. It is designed to be used in a pipeline for dynamic document retrieval (usually
without an indexed vector database) to find the most relevant documents on a given query.
"""

from typing import Any, Dict, List, Optional

import numpy as np
from haystack import component, default_from_dict, default_to_dict
from haystack.dataclasses import Document
from typing_extensions import Self

from ravelin.embedding_functions import EmbeddingFunction, RegisteredEmbeddingFunction, EmbeddingFunctionFactory


@component
class EmbeddingSimilarityRanker:
    """
    Ranks Documents based on their similarity to the query using an external embedding asset.

    :param embedding_function: The embedding function to use for the ranker.
    :param top_k:
        The maximum number of documents to return. If `None`, all documents are returned.
    :param score_threshold:
        Use it to return documents only with a score above this threshold.
    :param recompute_embeddings:
        If `True`, forces the recalculation of the embeddings for all documents even if they are already present.
        This might be useful if existing embeddings are generated by a different method.
    """

    def __init__(
        self,
        embedding_function: EmbeddingFunction,
        top_k: Optional[int] = None,
        score_threshold: Optional[float] = None,
        recompute_embeddings: Optional[bool] = None,
    ):
        self.embedding_function = embedding_function
        self.top_k = top_k
        self.score_threshold = score_threshold
        self.recompute_embeddings = recompute_embeddings

    def to_dict(self) -> Dict[str, Any]:
        """
        Returns a serialized dictionary representation of the component.

        :returns: A dictionary representation of the component.
        """
        if not isinstance(self.embedding_function, RegisteredEmbeddingFunction):
            raise ValueError("Embedding function must be a registered embedding function to be serialized.")
        return default_to_dict(
            self,
            embedding_function=self.embedding_function.to_dict(),
            top_k=self.top_k,
            score_threshold=self.score_threshold,
            recompute_embeddings=self.recompute_embeddings,
        )

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> Self:
        """
        Loads an EmbeddingSimilarityRanker component from its serialized dictionary representation.

        :param data: The serialized dictionary representation of the component.
        :returns: The deserialized EmbeddingSimilarityRanker component.
        """
        # Make a shallow copy of init_parameters to avoid modifying the original data
        init_parameters_data = data.get("init_parameters", {}).copy()

        # Load the embedding function from the factory
        embedding_function = EmbeddingFunctionFactory.create_from_dict(init_parameters_data["embedding_function"])
        init_parameters_data["embedding_function"] = embedding_function

        # Load the component
        return default_from_dict(cls, {"type": data["type"], "init_parameters": init_parameters_data})

    @component.output_types(documents=List[Document])
    def run(
        self,
        query: str,
        documents: List[Document],
        top_k: Optional[int] = None,
        score_threshold: Optional[float] = None,
        recompute_embeddings: Optional[bool] = None,
    ):
        """
        Returns a list of documents ranked by their similarity to the given query.

        :param query:
            The input query to compare the documents to.
        :param documents:
            A list of documents to be ranked.
        :param top_k:
            The maximum number of documents to return.
        :param score_threshold:
            Use it to return documents only with a score above this threshold.
        :param recompute_embeddings:
            If `True`, forces the recalculation of the embeddings for all documents even if they are already present.
        :returns:
            A dictionary with the following keys:
            - `documents`: A list of documents closest to the query, sorted from most similar to least similar.

        :raises ValueError:
            If `top_k` is not > 0.
        """
        # Override parameters with instance variables if not provided
        top_k = top_k if top_k is not None else self.top_k
        score_threshold = score_threshold if score_threshold is not None else self.score_threshold
        recompute_embeddings = recompute_embeddings if recompute_embeddings is not None else self.recompute_embeddings

        # Parameter validation
        if top_k is not None and top_k <= 0:
            raise ValueError("top_k must be > 0")

        if not documents:
            return {"documents": []}

        # Compute query embedding
        query_embedding = self.embedding_function([query])[0]

        # Collect documents that need embeddings
        docs_needing_embeddings = []
        docs_indices = []

        for i, doc in enumerate(documents):
            if doc.content and (recompute_embeddings or doc.embedding is None):
                docs_needing_embeddings.append(doc.content)
                docs_indices.append(i)

        # Compute embeddings for documents that need them
        if docs_needing_embeddings:
            # We will need to support batch processing in the future
            embeddings = self.embedding_function(docs_needing_embeddings)
            for i, embedding in zip(docs_indices, embeddings):
                if not (isinstance(embedding, list) and all(isinstance(x, float) for x in embedding)):
                    raise ValueError(
                        f"Embedding function {self.embedding_function} returned {type(embedding)} and is not supported."
                    )
                documents[i].embedding = embedding

        # Compute similarities and rank documents
        ranked_documents = []

        for doc in documents:
            if doc.embedding is not None:
                # Calculate cosine similarity
                doc_embedding = np.array(doc.embedding)
                query_embedding_array = np.array(query_embedding)

                similarity = np.dot(query_embedding_array, doc_embedding) / (
                    np.linalg.norm(query_embedding_array) * np.linalg.norm(doc_embedding)
                )

                # Update document score
                doc.score = float(similarity)
                ranked_documents.append(doc)

        # Sort by score in descending order
        ranked_documents = sorted(ranked_documents, key=lambda doc: doc.score or -float("inf"), reverse=True)

        # Filter by threshold
        if score_threshold is not None:
            ranked_documents = [
                doc for doc in ranked_documents if doc.score is not None and doc.score >= score_threshold
            ]

        # Limit to top-k
        if top_k is not None:
            ranked_documents = ranked_documents[:top_k]

        return {"documents": ranked_documents}
